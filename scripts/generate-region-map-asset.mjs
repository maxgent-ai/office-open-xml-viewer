#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const [input, output = 'packages/core/src/chart/region-map-natural-earth.generated.ts'] = process.argv.slice(2);
if (!input) throw new Error('usage: generate-region-map-asset.mjs <Natural Earth GeoJSON> [output]');

const inputBytes = await readFile(input);
const inputSha256 = createHash('sha256').update(inputBytes).digest('hex');
const expectedSha256 = '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f';
if (inputSha256 !== expectedSha256) {
  throw new Error(`unexpected Natural Earth source SHA-256: ${inputSha256}`);
}
const source = JSON.parse(inputBytes.toString('utf8'));
if (source?.type !== 'FeatureCollection' || !Array.isArray(source.features)) {
  throw new Error('expected a GeoJSON FeatureCollection');
}

const quantize = (value) => Math.round(Number(value) * 100) / 100;
const ring = (points) => {
  const result = [];
  for (const point of points) {
    if (!Array.isArray(point) || point.length < 2) continue;
    const next = [quantize(point[0]), quantize(point[1])];
    const previous = result.at(-1);
    if (!previous || previous[0] !== next[0] || previous[1] !== next[1]) result.push(next);
  }
  return result.length >= 3 ? result : null;
};
const polygons = (geometry) => {
  if (geometry?.type === 'Polygon') return [geometry.coordinates];
  if (geometry?.type === 'MultiPolygon') return geometry.coordinates;
  return [];
};

const features = source.features.flatMap((feature) => {
  const properties = feature.properties ?? {};
  const compactPolygons = polygons(feature.geometry)
    .map((polygon) => polygon.map(ring).filter(Boolean))
    .filter((polygon) => polygon.length > 0);
  if (compactPolygons.length === 0) return [];
  const code = (value) => typeof value === 'string' && value !== '-99' ? value : '';
  return [{
    n: String(properties.NAME_LONG ?? properties.ADMIN ?? properties.NAME ?? ''),
    a2: code(properties.ISO_A2),
    a3: code(properties.ISO_A3) || code(properties.ADM0_A3),
    p: code(properties.POSTAL),
    l: [quantize(properties.LABEL_X ?? 0), quantize(properties.LABEL_Y ?? 0)],
    g: compactPolygons,
  }];
});

const vertexCount = features.reduce(
  (sum, feature) => sum + feature.g.reduce(
    (polygonSum, polygon) => polygonSum + polygon.reduce((ringSum, value) => ringSum + value.length, 0),
    0,
  ),
  0,
);
if (features.length !== 177 || vertexCount > 20_000) {
  throw new Error(`unexpected Natural Earth asset bounds: ${features.length} features / ${vertexCount} vertices`);
}

const header = `// Generated by scripts/generate-region-map-asset.mjs from Natural Earth\n`
  + `// Admin 0 Countries, 1:110m. Source SHA-256:\n`
  + `// ${inputSha256}\n`
  + `// Natural Earth data is public domain. Coordinates are quantized to 0.01°.\n`
  + `export type RegionMapPoint = readonly [number, number];\n`
  + `export interface RegionMapFeature { readonly n:string; readonly a2:string; readonly a3:string; readonly p:string; readonly l:RegionMapPoint; readonly g:readonly (readonly (readonly RegionMapPoint[])[])[] }\n`
  + `export const NATURAL_EARTH_FEATURE_COUNT=${features.length};\n`
  + `export const NATURAL_EARTH_VERTEX_COUNT=${vertexCount};\n`
  + `export const NATURAL_EARTH_110M=${JSON.stringify(features)} as const satisfies readonly RegionMapFeature[];\n`;
await writeFile(output, header);
